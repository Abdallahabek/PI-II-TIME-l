-- Script de criacao das tabelas do Sistema de Acompanhamento de Demandas (Oracle)

CREATE TABLE usuarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nome VARCHAR2(120) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    senha VARCHAR2(255) NOT NULL,
    perfil VARCHAR2(30) NOT NULL,
    CONSTRAINT chk_usuarios_perfil CHECK (
        perfil IN ('Administrador', 'Líder de Projeto', 'Membro da Equipe')
    )
);

CREATE TABLE projetos (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    nome VARCHAR2(150) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    data_criacao DATE DEFAULT TRUNC(SYSDATE) NOT NULL
);

-- Vinculo entre usuarios e projetos para controle de acesso de Lideres e Membros
CREATE TABLE usuario_projeto (
    usuario_id NUMBER NOT NULL,
    projeto_id NUMBER NOT NULL,
    CONSTRAINT pk_usuario_projeto PRIMARY KEY (usuario_id, projeto_id),
    CONSTRAINT fk_up_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id),
    CONSTRAINT fk_up_projeto FOREIGN KEY (projeto_id) REFERENCES projetos(id)
);

CREATE TABLE demandas (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    titulo VARCHAR2(200) NOT NULL,
    descricao VARCHAR2(2000) NOT NULL,
    tipo VARCHAR2(20) NOT NULL,
    prioridade VARCHAR2(20) NOT NULL,
    status VARCHAR2(20) DEFAULT 'Aberta' NOT NULL,
    projeto_id NUMBER NOT NULL,
    responsavel_id NUMBER NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    data_atualizacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    prazo_finalizacao DATE NULL,
    CONSTRAINT chk_demandas_tipo CHECK (
        tipo IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentação')
    ),
    CONSTRAINT chk_demandas_prioridade CHECK (
        prioridade IN ('Crítica', 'Alta', 'Média', 'Baixa')
    ),
    CONSTRAINT chk_demandas_status CHECK (
        status IN ('Aberta', 'Em andamento', 'Em revisão', 'Concluída', 'Cancelada')
    ),
    CONSTRAINT fk_demandas_projeto FOREIGN KEY (projeto_id) REFERENCES projetos(id),
    CONSTRAINT fk_demandas_responsavel FOREIGN KEY (responsavel_id) REFERENCES usuarios(id)
);

CREATE TABLE comentarios (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    demanda_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    texto VARCHAR2(1000) NOT NULL,
    data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_comentarios_demanda FOREIGN KEY (demanda_id) REFERENCES demandas(id),
    CONSTRAINT fk_comentarios_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);

-- Registro de auditoria das alteracoes relevantes da demanda
CREATE TABLE historico_alteracoes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    demanda_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    campo_alterado VARCHAR2(50) NOT NULL,
    valor_anterior VARCHAR2(200) NULL,
    valor_novo VARCHAR2(200) NOT NULL,
    descricao VARCHAR2(500) NOT NULL,
    data_alteracao TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_hist_demanda FOREIGN KEY (demanda_id) REFERENCES demandas(id),
    CONSTRAINT fk_hist_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id)
);
